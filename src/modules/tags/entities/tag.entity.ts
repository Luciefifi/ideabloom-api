import {
  Column,
  CreateDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryGeneratedColumn,
} from 'typeorm';
import { User } from '../../users/entities/user.entity';

/** A free-form label. An idea can have many tags; a tag can be on many ideas. */
@Entity('tags')
@Index('UQ_tags_user_name_key', ['userId', 'nameKey'], { unique: true })
export class Tag {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Index('IDX_tags_user_id')
  @Column({ name: 'user_id', type: 'uuid' })
  userId: string;

  @ManyToOne(() => User, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'user_id' })
  user?: User;

  @Column({ type: 'varchar', length: 30 })
  name: string;

  /** lower(name), generated by PostgreSQL, for case-insensitive uniqueness. */
  @Column({
    name: 'name_key',
    type: 'varchar',
    length: 30,
    generatedType: 'STORED',
    asExpression: 'lower(name)',
    select: false,
    insert: false,
    update: false,
  })
  nameKey?: string;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;
}
